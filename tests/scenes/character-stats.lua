--@ title: Character: stats put away
--@ roots: PolestarUICharacter, PolestarUICharacterStats
PolestarUI.Show("character")
local probe = CreateFrame("Frame", nil, UIParent)
probe:SetSize(100, 100)
probe:Hide()
PolestarUI.Dock(probe)
probe:Show()
local open = select(4, probe:GetPoint(1))
PolestarUICharacter.psMenu:Click()
assert(PolestarMenu.rows[1].Check:IsShown(), "Show stats not checked")
PolestarMenu.rows[1]:Click()
assert(not PolestarUICharacterStats:IsShown(), "still shown")
assert(PolestarUIDB.hideStats, "not kept")
-- The window menu ("...") holds the option, then "Use game window", and shows its state again.
PolestarUICharacter.psMenu:Click()
assert(PolestarMenu.rows[1].psItem.text == "Show stats" and not PolestarMenu.rows[1].Check:IsShown(), "Show stats still checked")
assert(PolestarMenu.rows[2].psItem.text == "Use game window", "no Use game window after the options")
PolestarMenu.rows[1]:Click()
assert(PolestarUICharacterStats:IsShown() and not PolestarUIDB.hideStats, "not shown again")
PolestarUICharacter.psMenu:Click()
PolestarMenu.rows[1]:Click()
assert(open - select(4, probe:GetPoint(1)) == PolestarUICharacterStats:GetWidth() - 1, "the dock left no room for the drawer: " .. open .. " then " .. select(4, probe:GetPoint(1)))
probe:Hide()
