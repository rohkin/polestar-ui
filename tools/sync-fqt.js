'use strict';
// sync-fqt: regenerate Addons/ForeverQuestTintData.lua (the original-Classic quest ranges) from the installed
// ForeverQuestTint addon (its VanillaQuests.lua and .toc version). Prints "unchanged" or old -> new version.
// AddOns folder: as tools/link.js ($WOW_FOREVER_ADDONS, else the first _forever_ client found).

const fs = require('node:fs');
const path = require('node:path');
const { findAddons } = require('./link');

const OUT = path.resolve(__dirname, '..', 'Addons', 'ForeverQuestTintData.lua');
const fail = (m) => { console.error('sync-fqt: ' + m); process.exit(1); };

const addons = findAddons(process.env);
if (!addons) fail('no WoW Forever AddOns folder found (set WOW_FOREVER_ADDONS)');
const src = path.join(addons, 'ForeverQuestTint');
let toc, lua;
try {
	toc = fs.readFileSync(path.join(src, 'ForeverQuestTint.toc'), 'utf8');
	lua = fs.readFileSync(path.join(src, 'VanillaQuests.lua'), 'utf8');
} catch (e) { fail('cannot read ' + src + ': ' + e.message); }

const version = (toc.match(/^##\s*Version:\s*(\S+)/m) || [])[1] || fail('no ## Version in the .toc');
const body = (lua.match(/ns\.VanillaQuestRanges\s*=\s*\{([\s\S]*)\}\s*$/) || [])[1];
if (body === undefined) fail('VanillaQuests.lua: no `ns.VanillaQuestRanges = { ... }` at the end: the format changed');
const ranges = [...body.matchAll(/\{\s*(\d+)\s*,\s*(\d+)\s*\}/g)].map((m) => [+m[1], +m[2]]);
if (body.replace(/\{\s*\d+\s*,\s*\d+\s*\}/g, '').replace(/[\s,]/g, '') !== '') fail('VanillaQuests.lua: entries that are not {lo,hi}: the format changed');
if (ranges.length < 300) fail('VanillaQuests.lua: only ' + ranges.length + ' ranges: the format changed');
ranges.forEach(([lo, hi], i) => { if (lo > hi || (i && lo <= ranges[i - 1][1])) fail('VanillaQuests.lua: ranges not sorted at ' + lo + ': the binary search would break'); });

const rows = [];
for (let i = 0; i < ranges.length; i += 8) rows.push('\t' + ranges.slice(i, i + 8).map(([a, b]) => `{${a},${b}},`).join(''));
const text = `-- GENERATED by tools/sync-fqt.js (npm run sync:fqt): do not edit.
-- The quest IDs of original Classic, as the ForeverQuestTint addon lists them
-- (VanillaQuests.lua, generated there from Questie's Classic quest database),
-- copied so Addons/ForeverQuestTint.lua marks the same quests as that addon.
-- ForeverQuestTint is by xanastar, GPL-3; this data is under the same licence
-- as this addon (GPL-3.0-or-later).
local ADDON, ns = ...
ns.FQTData = {
	version = "${version}",
	ranges = {
${rows.join('\n')}
	},
}
`;
const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
const oldVersion = (old.match(/version = "([^"]*)"/) || [])[1];
if (old === text) console.log('unchanged (ForeverQuestTint ' + version + ', ' + ranges.length + ' ranges)');
else {
	fs.writeFileSync(OUT, text);
	console.log((oldVersion || 'none') + ' -> ' + version + ' (' + ranges.length + ' ranges)');
}
